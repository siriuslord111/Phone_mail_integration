const catalogs: Record<LanguageCode, Record<TranslationKey, string>> = { en, hi, ta, te, bn, mr };

export function readLanguage(): LanguageCode {
  if (typeof localStorage === 'undefined') return 'en';
  const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return LANGUAGES.some((item) => item.code === saved) ? saved as LanguageCode : 'en';
}

export function saveLanguage(language: LanguageCode) {
  localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

export function translate(key: TranslationKey, language: LanguageCode): string {
  return catalogs[language][key] ?? en[key];
}

export function getLanguageLabel(language: LanguageCode) {
  return LANGUAGES.find((item) => item.code === language)?.label ?? LANGUAGES[0].label;
}

export function isLanguageCode(value: string): value is LanguageCode {
  return LANGUAGES.some((item) => item.code === value);
}

export function getTranslationKeys(): TranslationKey[] {
  return Object.keys(en) as TranslationKey[];
}
